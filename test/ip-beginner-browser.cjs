const { chromium } = require(process.argv[2]);
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');

(async () => {
  process.env.NETWORK_LAB_DATA_DIR = await fs.mkdtemp(path.join(os.tmpdir(), 'kn-ip-beginner-'));
  const { createLabServer } = await import('../server.js');
  const server = createLabServer({ production: false, origin: '', proxy: '' });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1360, height: 1000 }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/fundamentals.html?course=addressing');
    await page.locator('#bit-builder').waitFor();
    assert.equal(await page.locator('#clear-octet svg').count(), 1, 'The reset control needs its visible icon');
    assert.equal(await page.locator('#check-binary svg').count(), 1);
    assert.equal(await page.locator('.ip-learning-path a').count(), 9);
    const run = async id => {
      const host = page.locator(id);
      for (let i = 0; i < 20 && await host.locator('[data-step]').isEnabled(); i++) await host.locator('[data-step]').click();
      return host.locator('.lesson-status').innerText();
    };
    await page.locator('[data-bit="5"]').click(); await page.locator('[data-bit="7"]').click();
    assert.equal(await page.locator('#built-binary').innerText(), '00000101');
    assert.equal(await page.locator('#built-decimal').innerText(), '5');
    await page.locator('#check-octet').click(); assert.match(await page.locator('#octet-feedback').innerText(), /Correct/);
    await page.locator('#clear-octet').click(); assert.equal(await page.locator('#built-decimal').innerText(), '0');
    await page.locator('[data-bit="0"]').focus(); await page.keyboard.press('Space');
    assert.equal(await page.locator('#built-decimal').innerText(), '128');
    assert.equal(await page.locator('[data-bit="0"]').getAttribute('aria-pressed'), 'true');

    const binary = page.locator('#binary-lab');
    await binary.locator('[data-step]').click();
    assert.match(await binary.locator('.octet-decision').innerText(), /128.*192[\s\S]*64 remaining/);
    assert.equal(await binary.locator('.current-bit').count(), 1);
    await binary.locator('[data-step]').click(); await binary.locator('[data-step]').click();
    assert.match(await binary.locator('.octet-decision').innerText(), /write 0/);
    await binary.locator('[data-replay-previous]').click();
    assert.match(await binary.locator('.lesson-status').innerText(), /Step 2/);
    assert.match(await run('#binary-lab'), /192 decimal = 11000000 binary/);
    await page.locator('#conversion-mode').selectOption('binary'); await page.locator('#conversion-value').fill('00011111');
    assert.match(await run('#binary-lab'), /31 decimal = 00011111 binary/);
    await page.locator('#binary-prediction').fill('31'); await page.locator('#check-binary').click();
    assert.match(await page.locator('#binary-feedback').innerText(), /Correct/);
    assert.match(await binary.locator('.lesson-status').innerText(), /31 decimal = 00011111 binary/, 'Prediction entry must not rewind the animation');
    await page.locator('#conversion-value').fill('00011112');
    assert.match(await binary.locator('.lesson-status').innerText(), /eight binary digits/);
    assert.equal(await binary.locator('[data-step]').isDisabled(), true);
    await page.locator('#conversion-value').fill('00011111');

    assert.match(await run('#class-cidr-lab'), /192.168.10.127.*62/);
    assert.equal(await page.locator('#class-cidr-lab .bit-network').count(), 26);
    assert.equal(await page.locator('#class-cidr-lab .bit-host').count(), 6);
    await page.locator('.ip-learning-path a[href$="#host-sizing-lab"]').click();
    assert.match(page.url(), /course=addressing#host-sizing-lab/);
    assert.equal(await page.locator('#conversion-value').inputValue(), '00011111', 'Topic navigation must not remount the lesson and erase work');
    assert.match(await run('#host-sizing-lab'), /Choose \/26.*62/);
    await page.locator('#required-hosts').fill('63'); assert.match(await run('#host-sizing-lab'), /Choose \/25/);
    await page.locator('#required-hosts').fill('0'); assert.equal(await page.locator('#host-sizing-lab [data-step]').isDisabled(), true);
    await page.locator('#required-hosts').fill('50');
    assert.match(await run('#subnet-split-lab'), /4 blocks x 64 addresses = 256/);
    assert.match(await page.locator('.split-work').innerText(), /192.168.10.192\/26/);
    await page.locator('#split-child').fill('23'); assert.match(await page.locator('#subnet-split-lab .lesson-status').innerText(), /smaller slash/);
    await page.locator('#split-child').fill('26');
    assert.match(await run('#vlsm-lab'), /Allocated 112.*144/);
    assert.match(await page.locator('.vlsm-work').innerText(), /192.168.10.96\/28/);
    await page.locator('#vlsm-parent').fill('192.168.10.0/26');
    assert.match(await page.locator('#vlsm-lab .lesson-status').innerText(), /do not fit/);
    assert.equal(await page.locator('#vlsm-lab [data-step]').isDisabled(), true);
    await page.locator('#vlsm-parent').fill('192.168.10.0/24');
    assert.match(await run('#aggregate-lab'), /Exact summary/);
    await page.locator('#summary-right').fill('192.168.11.0/25');
    assert.match(await run('#aggregate-lab'), /256 extra addresses/);

    const scenario = await page.locator('#practice-scenario').innerText();
    const [ip, length] = scenario.split('/'), prefix = Number(length);
    const numeric = ip.split('.').reduce((sum, octet) => sum * 256 + Number(octet), 0);
    const size = 2 ** (32 - prefix), network = Math.floor(numeric / size) * size;
    const decimal = n => [24, 16, 8, 0].map(shift => Math.floor(n / 2 ** shift) % 256).join('.');
    const answers = { mask: decimal(2 ** 32 - size), network: decimal(network), broadcast: decimal(network + size - 1), total: String(size), usable: String(size - 2) };
    for (const [key, value] of Object.entries(answers)) await page.locator('#answer-' + key).fill(key === 'network' ? ip : value);
    await page.locator('#cidr-practice-form button[type="submit"]').click();
    assert.match(await page.locator('#cidr-practice-feedback').innerText(), /4\/5.*network: Clear/);
    assert.equal(await page.locator('#answer-network').getAttribute('aria-invalid'), 'true');
    await page.locator('#answer-network').fill(answers.network);
    await page.locator('#cidr-practice-form button[type="submit"]').click();
    assert.match(await page.locator('#cidr-practice-feedback').innerText(), /Attempt 2: 5\/5/);
    await page.locator('#new-cidr-practice').click();
    assert.notEqual(await page.locator('#practice-scenario').innerText(), scenario);
    assert.equal(await page.locator('#answer-network').inputValue(), '');
    assert.equal(await page.locator('#cidr-practice [aria-invalid]').count(), 0);
    assert.equal((await page.request.get(base + '/api/assessment')).status(), 401);

    await page.locator('#cidr-example').selectOption('10.20.30.40/12');
    assert.match(await run('#class-cidr-lab'), /10.31.255.255/);
    await page.locator('#cidr-example').selectOption('172.16.35.10/20');
    assert.match(await run('#class-cidr-lab'), /172.16.47.255.*4094/);
    await fs.mkdir('artifacts', { recursive: true });
    await page.locator('#class-cidr-lab').screenshot({ path: 'artifacts/ip-beginner-cidr-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.locator('.and-octets section').count(), 4);
    assert.ok(await page.locator('.and-octets code').evaluateAll(codes => codes.every(code => getComputedStyle(code).whiteSpace === 'nowrap')));
    await page.locator('#bit-builder').screenshot({ path: 'artifacts/ip-beginner-builder-mobile.png' });
    await binary.locator('[data-step]').click();
    await binary.screenshot({ path: 'artifacts/ip-beginner-conversion-mobile.png' });
    await page.locator('#class-cidr-lab').screenshot({ path: 'artifacts/ip-beginner-cidr-mobile.png' });
    assert.ok(await page.locator('#ip-start img').evaluate(image => image.complete && image.naturalWidth > 0));
    await page.locator('#class-prefix').fill('31'); await run('#class-cidr-lab');
    assert.match(await page.locator('#class-cidr-lab .calculation-work').innerText(), /Point-to-point/);
    await page.locator('#class-prefix').fill('32'); assert.match(await run('#class-cidr-lab'), /One address/);
    await page.locator('#class-prefix').fill('');
    assert.equal(await page.locator('#class-cidr-lab [data-step]').isDisabled(), true);
    await page.locator('#cidr-example').selectOption('0.0.0.0/0');
    assert.match(await run('#class-cidr-lab'), /default route.*4294967296.*capacity: not applicable/);
    const defaultRouteWork = await page.locator('#class-cidr-lab .calculation-work').innerText();
    assert.match(defaultRouteWork, /Assignable count\s+Not applicable/);
    assert.doesNotMatch(defaultRouteWork, /4294967294|Ordinary broadcast LAN/);

    const extension = page.locator('section.module-lab').filter({ has: page.locator('#family') });
    const extensionStatus = extension.locator('.module-result');
    const nextPrefixStep = extension.locator('[data-next]');
    await page.locator('#cidr').fill('192.168.10.70/0');
    for (let i = 0; i < 4; i++) await nextPrefixStep.click();
    assert.match(await extensionStatus.innerText(), /default route.*capacity: not applicable/);
    await page.locator('#family').selectOption('6');
    for (let i = 0; i < 3; i++) await nextPrefixStep.click();
    assert.match(await extensionStatus.innerText(), /2001:db8:1234:5::\/64/);
    await page.locator('#cidr').fill('1:2:3:4:5:6:7:8::/64');
    assert.match(await extensionStatus.innerText(), /Enter a valid IPv6 address/);
    assert.equal(await nextPrefixStep.isDisabled(), true);
    assert.equal(await extension.locator('.prefix-bits span').count(), 0);
    await page.locator('#cidr').fill('2001:db8:1234:6::42/48');
    for (let i = 0; i < 3; i++) await nextPrefixStep.click();
    assert.match(await extensionStatus.innerText(), /2001:db8:1234::\/48/);

    const repair = page.locator('#address-repair-lab');
    const repairResult = repair.locator('#repair-result');
    const probe = repair.getByRole('button', { name: 'Run both pings' });
    await probe.click();
    assert.match(await repairResult.innerText(), /Local peer\s+Passed/);
    assert.match(await repairResult.innerText(), /Engineering peer\s+Failed/);
    await repair.locator('#repair-prefix').fill('27');
    assert.equal(await repairResult.innerText(), '');
    await probe.click();
    assert.match(await repairResult.innerText(), /Engineering peer\s+Passed/);
    assert.match(await repairResult.innerText(), /does not match the Sales plan/);
    assert.match(await repairResult.innerText(), /Repair not yet verified/);
    await repair.locator('#repair-prefix').fill('26');
    await probe.focus();
    await page.keyboard.press('Enter');
    assert.match(await repairResult.innerText(), /Repair verified/);
    assert.equal(await repairResult.evaluate(node => node.scrollWidth > node.clientWidth), false);
    await repair.screenshot({ path: 'artifacts/ip-address-repair-mobile.png' });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Beginner IP browser checks passed: conversions, CIDR, practice, IPv4 /0 and host ranges, IPv6 validation and recovery, wrong-prefix repair with positive and negative probes, keyboard, reduced motion and mobile layout.');
  } finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
})().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
