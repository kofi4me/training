const { chromium } = require(process.argv[2]);
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } }); const errors = [];
    page.setDefaultTimeout(20000); page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:4317/index.html', { waitUntil: 'domcontentloaded' });
    const select = async id => { await page.locator('#device-picker').selectOption(id); };
    await select('pc-1'); await page.locator('[data-host-mode="compose"]').click();
    await page.locator('#host-destination').selectOption('pc-3');
    await page.locator('[data-draft="subject"]').fill('Network investigation');
    const body = 'Hello Engineering.\nPlease verify the VLAN. <img src=x onerror=alert(1)>';
    await page.locator('[data-draft="body"]').fill(body);
    await page.getByRole('button', { name: 'Send email', exact: true }).click();
    await page.getByText('Email delivered', { exact: true }).waitFor();
    assert.equal(await page.locator('[data-node="pc-3"] .mail-badge').count(), 1);
    await select('pc-3'); await page.locator('[data-host-mode="inbox"]').click();
    await page.locator('.mail-item').click();
    assert.equal(await page.locator('.mail-body').textContent(), body);
    assert.equal(await page.locator('.mail-body img').count(), 0);
    assert.equal(await page.locator('[data-node="pc-3"] .mail-badge').count(), 0);
    await page.getByRole('button', { name: 'Reply', exact: true }).click();
    assert.equal(await page.locator('#host-destination').inputValue(), 'pc-1');
    await page.locator('[data-draft="body"]').fill('Confirmed. Configuration received.');
    await page.getByRole('button', { name: 'Send email', exact: true }).click();
    assert.equal(await page.locator('#source').inputValue(), 'pc-3');
    assert.equal(await page.locator('#target').inputValue(), 'pc-1');
    await page.reload(); await select('pc-1'); await page.locator('[data-host-mode="inbox"]').click();
    await page.locator('.mail-item').click();
    assert.equal(await page.locator('.mail-body').textContent(), 'Confirmed. Configuration received.');
    await page.screenshot({ path: path.join(__dirname, '../artifacts/mail-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.locator('.host-tools').screenshot({ path: path.join(__dirname, '../artifacts/mail-mobile.png') });
    await select('router'); await page.locator('[data-field="routing"]').uncheck();
    await select('pc-1'); await page.locator('[data-host-mode="compose"]').click();
    await page.locator('#host-destination').selectOption('pc-3');
    await page.locator('[data-draft="body"]').fill('This must not arrive.');
    await page.getByRole('button', { name: 'Send email', exact: true }).click();
    await page.getByText('Email not delivered', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('network-workshop-v1')).messages.length), 2);
    await page.locator('[data-host-mode="ping"]').click();
    await page.locator('#host-destination').selectOption('pc-2');
    await page.locator('#host-message-form').getByRole('button', { name: 'Send ping', exact: true }).click();
    await page.getByText('Echo reply received', { exact: true }).waitFor();
    assert.deepEqual(errors, []);
    console.log('Mail browser checks passed: PC compose, delivery, inbox opening, unread indicators, literal text, replies, persistence, routing failure, local ping, mobile layout.');
  } finally { console.log('Closing mail test browser.');await browser.close();console.log('Mail test browser closed.'); }
})().then(()=>process.exit(0),error=>{console.error(error);process.exit(1);});
